// Translate only application-authored text and explicitly identified status messages.
// Account names, game names, server names, item descriptions, and input values stay untouched.
function savedLanguage() {
  try { return localStorage.getItem('steam-ui-language') === 'zh-CN' ? 'zh-CN' : 'en'; }
  catch { return 'en'; }
}
export const language = savedLanguage();
export const locale = language === 'en' ? 'en-US' : 'zh-CN';
const substitute = (source, values) => source.replace(/\{(\d+)\}/g, (match, index) => index < values.length ? String(values[index] ?? '') : match);
const escapeExpression = source => source.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const messagePatterns = Object.entries(translations).filter(([key]) => /\{\d+\}/.test(key)).map(([key, value]) => {
  const indices = [];
  const pieces = key.split(/(\{\d+\})/).map(piece => {
    const match = piece.match(/^\{(\d+)\}$/);
    if (!match) return escapeExpression(piece);
    indices.push(Number(match[1])); return '([\\s\\S]*?)';
  });
  return { expression: new RegExp(`^${pieces.join('')}$`), indices, value };
});
export function tr(source, ...values) {
  if (Array.isArray(source)) {
    const key = source.map((part, index) => part + (index < values.length ? `{${index}}` : '')).join('');
    return substitute(language === 'en' ? translations[key] ?? key : key, values);
  }
  if (typeof source !== 'string' || language !== 'en') return source;
  if (Object.hasOwn(translations, source)) return translations[source];
  if (!/\p{Script=Han}/u.test(source)) return source;
  for (const { expression, indices, value } of messagePatterns) {
    const match = source.match(expression);
    if (!match) continue;
    const argumentsByIndex = [];
    indices.forEach((index, capture) => { argumentsByIndex[index] = tr(match[capture + 1]); });
    return substitute(value, argumentsByIndex);
  }
  return source;
}

function initialize() {
  document.documentElement.lang = language;
  // Only the initial static document is translated. No observer rewrites later user data.
  const walker = document.createTreeWalker(document, NodeFilter.SHOW_TEXT);
  for (let current = walker.nextNode(); current; current = walker.nextNode()) {
    const parent = current.parentElement;
    if (!parent || parent.closest('script, style, textarea, [data-language]')) continue;
    const source = current.nodeValue, trimmed = source.trim();
    if (Object.hasOwn(translations, trimmed)) current.nodeValue = source.replace(trimmed, tr(trimmed));
  }
  for (const element of document.querySelectorAll('[aria-label], [placeholder], [alt], [title]')) {
    if (element.closest('[data-language]')) continue;
    for (const attribute of ['aria-label', 'placeholder', 'alt', 'title']) {
      if (element.hasAttribute(attribute)) element.setAttribute(attribute, tr(element.getAttribute(attribute)));
    }
  }
  for (const section of document.querySelectorAll('[data-language]')) section.hidden = section.dataset.language !== language;
  if (document.querySelector('.project-guide')) document.title = language === 'en' ? 'Project Guide · Rust Connection Research' : '项目说明 · Rust 连接研究';
  const bar = document.querySelector('.topbar');
  if (!bar || bar.querySelector('#ui-language')) return;
  const control = document.createElement('label'); control.className = 'language-control';
  const caption = document.createElement('span'); caption.textContent = tr('语言');
  const select = document.createElement('select'); select.id = 'ui-language'; select.setAttribute('aria-label', tr('语言'));
  for (const [value, label] of [['en', 'English'], ['zh-CN', '简体中文']]) {
    const option = document.createElement('option'); option.value = value; option.textContent = label; select.append(option);
  }
  select.value = language;
  select.addEventListener('change', () => {
    try { localStorage.setItem('steam-ui-language', select.value); }
    catch { return; }
    window.location.reload();
  });
  control.append(caption, select); bar.append(control);
}
if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initialize, { once: true });
  else initialize();
}
